-- KiosGame: database sistem top up game
-- Import file ini lewat phpMyAdmin (tab Import) atau: mysql -u root < database.sql

CREATE DATABASE IF NOT EXISTS db_topup_game CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE db_topup_game;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS transaksi;
DROP TABLE IF EXISTS metode_pembayaran;
DROP TABLE IF EXISTS produk;
DROP TABLE IF EXISTS games;
DROP TABLE IF EXISTS admin;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE admin (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(80) NOT NULL,
  username VARCHAR(40) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE games (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(80) NOT NULL,
  slug VARCHAR(80) NOT NULL UNIQUE,
  publisher VARCHAR(80) NOT NULL,
  warna CHAR(7) NOT NULL DEFAULT '#4c3ff0',
  label_id VARCHAR(30) NOT NULL DEFAULT 'User ID',
  butuh_server TINYINT(1) NOT NULL DEFAULT 0,
  label_server VARCHAR(30) NULL,
  aktif TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE produk (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  game_id INT UNSIGNED NOT NULL,
  nama_item VARCHAR(80) NOT NULL,
  harga_modal INT UNSIGNED NOT NULL,
  harga_jual INT UNSIGNED NOT NULL,
  aktif TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_produk_game FOREIGN KEY (game_id) REFERENCES games(id) ON DELETE CASCADE,
  INDEX idx_produk_game (game_id)
) ENGINE=InnoDB;

CREATE TABLE metode_pembayaran (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(50) NOT NULL,
  tipe ENUM('qris','ewallet','bank') NOT NULL,
  tujuan VARCHAR(120) NOT NULL,
  biaya_admin INT UNSIGNED NOT NULL DEFAULT 0,
  aktif TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB;

CREATE TABLE transaksi (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  kode VARCHAR(20) NOT NULL UNIQUE,
  game_id INT UNSIGNED NOT NULL,
  produk_id INT UNSIGNED NOT NULL,
  metode_id INT UNSIGNED NOT NULL,
  user_game_id VARCHAR(40) NOT NULL,
  server_game VARCHAR(20) NULL,
  nama_pelanggan VARCHAR(80) NULL,
  kontak VARCHAR(20) NOT NULL,
  harga_modal INT UNSIGNED NOT NULL,
  harga_jual INT UNSIGNED NOT NULL,
  biaya_admin INT UNSIGNED NOT NULL DEFAULT 0,
  total INT UNSIGNED NOT NULL,
  status ENUM('pending','dibayar','sukses','gagal','batal') NOT NULL DEFAULT 'pending',
  catatan VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_trx_game FOREIGN KEY (game_id) REFERENCES games(id),
  CONSTRAINT fk_trx_produk FOREIGN KEY (produk_id) REFERENCES produk(id),
  CONSTRAINT fk_trx_metode FOREIGN KEY (metode_id) REFERENCES metode_pembayaran(id),
  INDEX idx_trx_status (status),
  INDEX idx_trx_created (created_at)
) ENGINE=InnoDB;

